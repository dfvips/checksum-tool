    public static string Get(Language language, string key)
    {
        if (!Table.TryGetValue(key, out string[]? values))
        {
            return key;
        }

        int index = (int)language;
        if (index >= 0 && index < values.Length && !string.IsNullOrWhiteSpace(values[index]))
        {
            return values[index];
        }

        // 该语言缺失文案时回退到英语，再不行回退到第一条
        int english = (int)Language.English;
        if (english < values.Length && !string.IsNullOrWhiteSpace(values[english]))
        {
            return values[english];
        }

        return values.Length > 0 ? values[0] : key;
    }

